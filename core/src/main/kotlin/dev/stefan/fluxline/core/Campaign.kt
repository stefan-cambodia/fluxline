    val size: Int get() = DEFS.size

    /** Le niveau [number] (à partir de 1). */
    fun level(number: Int): LevelSpec {
        val def = DEFS[(number - 1).coerceIn(0, DEFS.size - 1)]
        return LevelSpec(
            id = "level-$number",
            title = def.title,
            layout = def.layout.trimIndent().lines().map { it.trim() }.filter { it.isNotEmpty() },
            target = def.target,
            countdown = def.countdown,
            secondsPerCell = def.secondsPerCell,
            queueSeed = Rng.mix(0xF1u.toLong(), number.toLong()),
            allowRotation = true,
            requireDrain = def.requireDrain,
        )
    }

    fun all(): List<LevelSpec> = (1..size).map { level(it) }
}
